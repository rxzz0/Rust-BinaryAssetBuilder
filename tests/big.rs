use binary_asset_builder::big::{pack_big, stage_big};
use std::fs;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

#[test]
fn matches_makebig_and_reuses_only_identical_contents() {
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let root = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("bab-big-{}-{nonce}", std::process::id()));
    let input = root.join("input");
    let output = root.join("out.big");
    fs::create_dir_all(input.join("Abc")).unwrap();
    fs::create_dir(input.join("def")).unwrap();
    let files: &[(&str, &[u8])] = &[
        ("a.txt", b"abc"),
        ("z.txt", b"z"),
        ("Abc/C.BIN", b"hello"),
        ("Abc/a.asset", b"excluded"),
        ("Abc/b.ASSET", b"excluded"),
        ("def/a.bin", b"r"),
        ("def/zero.dat", b""),
    ];
    for &(name, content) in files {
        fs::write(input.join(name), content).unwrap();
    }

    let packed = pack_big(&input, &output).unwrap();
    assert_eq!(packed.entries, 5);
    assert!(!packed.reused);
    // Generated by the RA3 SDK MakeBig.exe with -x:*.asset.
    let expected = b"BIG4\x77\0\0\0\0\0\0\x05\0\0\0\x6d\
        \0\0\0\x6d\0\0\0\x05abc\\c.bin\0\
        \0\0\0\x72\0\0\0\x01def\\a.bin\0\
        \0\0\0\x73\0\0\0\0def\\zero.dat\0\
        \0\0\0\x73\0\0\0\x03a.txt\0\
        \0\0\0\x76\0\0\0\x01z.txt\0L219\0\0\0\0hellorabcz";
    assert_eq!(fs::read(&output).unwrap(), expected);
    assert!(pack_big(&input, &output).unwrap().reused);
    let staged = root.join("staged.big");
    assert!(stage_big(&input, &staged, &output).unwrap().reused);
    assert!(!staged.exists());
    fs::write(input.join("a.txt"), b"xyz").unwrap();
    assert!(!stage_big(&input, &staged, &output).unwrap().reused);
    assert!(fs::read(&staged).unwrap().ends_with(b"hellorxyzz"));
    assert_eq!(fs::read(&output).unwrap(), expected);
    fs::remove_file(staged).unwrap();
    assert!(!pack_big(&input, &output).unwrap().reused);
    assert!(fs::read(&output).unwrap().ends_with(b"hellorxyzz"));

    for &(name, _) in files {
        fs::remove_file(input.join(name)).unwrap();
    }
    fs::remove_file(output).unwrap();
    fs::remove_dir(input.join("Abc")).unwrap();
    fs::remove_dir(input.join("def")).unwrap();
    fs::remove_dir(input).unwrap();
    fs::remove_dir(root).unwrap();
}
