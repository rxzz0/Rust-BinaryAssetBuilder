use binary_asset_builder::big::{pack_big, stage_big};
use std::fs;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

#[test]
fn matches_makebig_and_reuses_only_identical_contents() {
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let root = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("bab-big-{}-{nonce}", std::process::id()));
    let input = root.join("input");
    let output = root.join("out.big");
    fs::create_dir_all(input.join("Abc")).unwrap();
    fs::create_dir(input.join("def")).unwrap();
    let files: &[(&str, &[u8])] = &[
        ("a.txt", b"abc"),
        ("z.txt", b"z"),
        ("Abc/C.BIN", b"hello"),
        ("Abc/a.asset", b"excluded"),
        ("Abc/b.ASSET", b"excluded"),
        ("def/a.bin", b"r"),
        ("def/zero.dat", b""),
    ];
    for &(name, content) in files {
        fs::write(input.join(name), content).unwrap();
    }

    let packed = pack_big(&input, &output).unwrap();
    assert_eq!(packed.entries, 5);
    assert!(!packed.reused);
    // Generated by the RA3 SDK MakeBig.exe with -x:*.asset.
    let expected = b"BIG4\x77\0\0\0\0\0\0\x05\0\0\0\x6d\
        \0\0\0\x6d\0\0\0\x05abc\\c.bin\0\
        \0\0\0\x72\0\0\0\x01def\\a.bin\0\
        \0\0\0\x73\0\0\0\0def\\zero.dat\0\
        \0\0\0\x73\0\0\0\x03a.txt\0\
        \0\0\0\x76\0\0\0\x01z.txt\0L219\0\0\0\0hellorabcz";
    assert_eq!(fs::read(&output).unwrap(), expected);
    assert!(pack_big(&input, &output).unwrap().reused);
    let staged = root.join("staged.big");
    assert!(stage_big(&input, &staged, &output).unwrap().reused);
    assert!(!staged.exists());
    fs::write(input.join("a.txt"), b"xyz").unwrap();
    assert!(!stage_big(&input, &staged, &output).unwrap().reused);
    assert!(fs::read(&staged).unwrap().ends_with(b"hellorxyzz"));
    assert_eq!(fs::read(&output).unwrap(), expected);
    fs::remove_file(staged).unwrap();
    assert!(!pack_big(&input, &output).unwrap().reused);
    assert!(fs::read(&output).unwrap().ends_with(b"hellorxyzz"));

    for &(name, _) in files {
        fs::remove_file(input.join(name)).unwrap();
    }
    fs::remove_file(output).unwrap();
    fs::remove_dir(input.join("Abc")).unwrap();
    fs::remove_dir(input.join("def")).unwrap();
    fs::remove_dir(input).unwrap();
    fs::remove_dir(root).unwrap();
}

#[test]
fn packs_configured_map_folders_at_official_paths() {
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let root = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("bab-misc-big-{}-{nonce}", std::process::id()));
    let mod_directory = root.join("SDK/Mods/Reborn");
    let external = root.join("Shared Maps");
    let expected = root.join("expected");
    let output = root.join("out.big");
    let standard = root.join("expected.big");
    let staged = root.join("staged.big");
    let misc = mod_directory.join("Misc");
    let custom = mod_directory.join("Data/Custom Maps");
    let local = misc.join("Alternate Maps");
    let config = mod_directory.join("mapdir.toml");
    let command = |output: &Path, previous: &Path| {
        std::process::Command::new(env!("CARGO_BIN_EXE_binary-asset-builder"))
            .arg("pack-misc-big")
            .arg(&mod_directory)
            .arg("--output")
            .arg(output)
            .arg("--reuse")
            .arg(previous)
            .output()
            .unwrap()
    };
    let write = |base: &Path, name: &str, bytes: &[u8]| {
        let path = base.join(name);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, bytes).unwrap();
    };
    for (source, path, packed, bytes) in [
        (
            &custom,
            "Alpha/an.asset",
            "data/maps/official/Alpha/an.asset",
            &b"excluded"[..],
        ),
        (
            &custom,
            "Alpha/map.version",
            "data/maps/official/Alpha/map.version",
            b"_mod\r\n",
        ),
        (
            &custom,
            "Alpha/alpha.map",
            "data/maps/official/Alpha/alpha.map",
            b"terrain",
        ),
        (
            &custom,
            "Alpha/Art/alpha.w3x",
            "data/maps/official/Alpha/Art/alpha.w3x",
            b"art",
        ),
        (
            &external,
            "Beta/map_mod.manifest",
            "data/maps/official/Beta/map_mod.manifest",
            b"manifest",
        ),
        (
            &external,
            "Beta/beta.map",
            "data/maps/official/Beta/beta.map",
            b"beta terrain",
        ),
    ] {
        write(source, path, bytes);
        write(&expected, packed, bytes);
    }
    write(&external, "Notes/readme.txt", b"unrelated");
    fs::write(
        &config,
        format!("Data/Custom Maps/\n{}\n", external.display()),
    )
    .unwrap();
    let result = command(&output, &output);
    assert!(result.status.success(), "{result:?}");
    pack_big(&expected, &standard).unwrap();
    assert_eq!(fs::read(&output).unwrap(), fs::read(&standard).unwrap());

    for (source, path, packed, bytes) in [
        (
            &misc,
            "data/maps/official/Stock/stock.map",
            "data/maps/official/Stock/stock.map",
            &b"stock"[..],
        ),
        (&misc, "root.txt", "root.txt", b"misc"),
        (
            &local,
            "Gamma/gamma.map",
            "data/maps/official/Gamma/gamma.map",
            b"gamma",
        ),
    ] {
        write(source, path, bytes);
        write(&expected, packed, bytes);
    }
    fs::write(
        &config,
        format!(
            "Data/Custom Maps/\n{}\nMisc/Alternate Maps\n",
            external.display()
        ),
    )
    .unwrap();
    let result = command(&output, &output);
    assert!(result.status.success(), "{result:?}");
    pack_big(&expected, &standard).unwrap();
    let expected = fs::read(&standard).unwrap();
    assert_eq!(fs::read(&output).unwrap(), expected);
    let result = command(&staged, &output);
    assert!(result.status.success(), "{result:?}");
    assert!(!staged.exists());

    write(&external, "aLPHA/map.xml", b"ambiguous");
    let result = command(&output, &output);
    assert!(!result.status.success(), "{result:?}");
    assert!(String::from_utf8_lossy(&result.stderr).contains("map folder \"alpha\""));
    assert_eq!(fs::read(&output).unwrap(), expected);
    fs::remove_dir_all(root).unwrap();
}
